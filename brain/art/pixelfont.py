ALIASES = {"❤": "♥", "❤️": "♥", "<": "♥"}   # "<3" types easily


def normalize(text: str) -> str:
    out = []
    skip = False
    for i, ch in enumerate(text.upper()):
        if skip:
            skip = False
            continue
        if ch == "<" and i + 1 < len(text) and text[i + 1] == "3":
            out.append("♥")
            skip = True
        else:
            out.append(ALIASES.get(ch, ch))
    return "".join(out)


def glyph(ch: str):
    return FONT.get(ch, FONT["_BOX"])


def text_width(text: str, scale: int = 1) -> int:
    """Total pixel width including 1-column gaps."""
    n = len(text)
    return (n * 5 + max(0, n - 1)) * scale


def draw_text(canvas: np.ndarray, text: str, x: int, y: int,
              color, scale: int = 1):
    """Stamp text onto an HxWx3 uint8 canvas at (x, y), clipping freely."""
    h, w = canvas.shape[:2]
    cx = x
    for ch in text:
        rows = glyph(ch)
        for ry, mask in enumerate(rows):
            for rx in range(5):
                if not mask & (1 << (4 - rx)):
                    continue
                px = cx + rx * scale
                py = y + ry * scale
                for sy in range(scale):
                    for sx in range(scale):
                        xx, yy = px + sx, py + sy
                        if 0 <= xx < w and 0 <= yy < h:
                            canvas[yy, xx] = color
        cx += 6 * scale
