# "<3" becomes a heart via the two-character rule in normalize(); a lone "<"
# is now a real glyph and must stay one.
ALIASES = {"❤": "♥", "❤️": "♥"}


def normalize(text: str) -> str:
    out = []
    skip = False
    for i, ch in enumerate(text):
        if skip:
            skip = False
            continue
        if ch == "<" and i + 1 < len(text) and text[i + 1] == "3":
            out.append("♥")
            skip = True
        else:
            out.append(ALIASES.get(ch, ch))
    return "".join(out)


def glyph(ch: str):
    return FONT.get(ch, FONT["_BOX"])


# ---- Hangul --------------------------------------------------------------
# All 11,172 modern syllables plus the 51 compatibility jamo, baked from
# Galmuri7 (OFL) by Tools/gen_hangul.py into 7-row bitmasks, bit 6 leftmost,
# 7 columns wide, advance 8. Same vertical band as the ASCII glyphs, so the
# two scripts sit on one baseline and mix freely mid-line.
_HANGUL: bytes | None = None


def _hangul() -> bytes:
    global _HANGUL
    if _HANGUL is None:
        import os
        path = os.path.join(os.path.dirname(__file__), "hangul7.bin")
        try:
            with open(path, "rb") as fh:
                _HANGUL = fh.read()
        except OSError:
            _HANGUL = b""
    return _HANGUL


_WORLD: dict | None = None


def _world() -> dict:
    """The rest of the world, lazily: cp -> (advance, dy, rows). Baked by
    Tools/gen_worldfont.py from Galmuri7 and Misaki; see that file for the
    format and the reasoning."""
    global _WORLD
    if _WORLD is None:
        import os
        import struct
        table = {}
        path = os.path.join(os.path.dirname(__file__), "world7.bin")
        try:
            blob = open(path, "rb").read()
            i = 0
            while i + 7 <= len(blob):
                cp, adv, dy, n = struct.unpack_from(">IbbB", blob, i)
                i += 7
                table[cp] = (adv, dy, blob[i:i + n])
                i += n
        except OSError:
            pass
        _WORLD = table
    return _WORLD


def cell(ch: str):
    """(rows, width, advance, dy) for any letterable character, else None.
    ASCII is 5 wide advance 6; Hangul 7 wide advance 8; the world table is
    MSB-packed 8 wide with its own advance and vertical offset."""
    if ch in FONT and ch != "_BOX":
        return FONT[ch], 5, 6, 0
    cp = ord(ch)
    if 0xAC00 <= cp <= 0xD7A3:
        off = (cp - 0xAC00) * 7
    elif 0x3131 <= cp <= 0x3163:
        off = (11172 + cp - 0x3131) * 7
    else:
        w = _world().get(cp)
        if w is None:
            return None
        adv, dy, rows = w
        return rows, 8, adv, dy
    blob = _hangul()
    if len(blob) < off + 7:
        return None
    return blob[off:off + 7], 7, 8, 0


def text_width(text: str, scale: int = 1) -> int:
    """Total pixel width including 1-column gaps, both scripts."""
    total = 0
    for ch in text:
        c = cell(ch)
        total += c[2] if c else 6
    return max(0, total - 1) * scale


def draw_text(canvas: np.ndarray, text: str, x: int, y: int,
              color, scale: int = 1):
    """Stamp text onto an HxWx3 uint8 canvas at (x, y), clipping freely."""
    h, w = canvas.shape[:2]
    cx = x
    for ch in text:
        c = cell(ch)
        rows, width, advance, dy = c if c else (FONT["_BOX"], 5, 6, 0)
        for ry, mask in enumerate(rows):
            for rx in range(width):
                if not mask & (1 << (width - 1 - rx)):
                    continue
                px = cx + rx * scale
                py = y + (ry + dy) * scale
                for sy in range(scale):
                    for sx in range(scale):
                        xx, yy = px + sx, py + sy
                        if 0 <= xx < w and 0 <= yy < h:
                            canvas[yy, xx] = color
        cx += advance * scale
