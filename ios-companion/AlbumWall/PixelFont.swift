    static let box: [UInt8] = [0x1F, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1F]

    static func normalize(_ text: String) -> String {
        var out = ""
        var skip = false
        let chars = Array(text.uppercased())
        for (i, ch) in chars.enumerated() {
            if skip { skip = false; continue }
            if ch == "<", i + 1 < chars.count, chars[i + 1] == "3" {
                out.append("♥"); skip = true
            } else if ch == "❤" || ch == "♥" {
                out.append("♥")
            } else {
                out.append(ch)
            }
        }
        return out
    }

    static func width(_ text: String, scale: Int = 1) -> Int {
        let n = text.count
        return (n * 5 + max(0, n - 1)) * scale
    }

    /// Stamp text into a 64x64 RGB buffer at (x, y), clipping freely.
    static func draw(_ text: String, into px: inout [UInt8],
                     x: Int, y: Int, rgb: (UInt8, UInt8, UInt8),
                     scale: Int = 2) {
        var cx = x
        for ch in text {
            let rows = glyphs[ch] ?? box
            for (ry, mask) in rows.enumerated() {
                for rx in 0..<5 where mask & (1 << (4 - rx)) != 0 {
                    for sy in 0..<scale {
                        for sx in 0..<scale {
                            let xx = cx + rx * scale + sx
                            let yy = y + ry * scale + sy
                            guard (0..<64).contains(xx),
                                  (0..<64).contains(yy) else { continue }
                            let i = (yy * 64 + xx) * 3
                            px[i] = rgb.0; px[i + 1] = rgb.1; px[i + 2] = rgb.2
                        }
                    }
                }
            }
            cx += 6 * scale
        }
    }

    /// One 64x64 ticker frame at scroll offset — twin of Ticker.frame_at.
    static func tickerFrame(text: String, offset: Int,
                            rgb: (UInt8, UInt8, UInt8)) -> UIImage? {
        var px = [UInt8](repeating: 0, count: 64 * 64 * 3)
        draw(text, into: &px, x: 64 - offset, y: (64 - 14) / 2, rgb: rgb)
        return UIImage.fromRGB64(Data(px))
    }

    /// One 64x64 clock frame for the current time — twin of Clock.frame_at.
    static func clockFrame(twentyFour: Bool,
                           rgb: (UInt8, UInt8, UInt8)) -> UIImage? {
        var px = [UInt8](repeating: 0, count: 64 * 64 * 3)
        let now = Calendar.current.dateComponents(
            [.hour, .minute, .second], from: Date())
        var hour = now.hour ?? 0
        var suffix: String? = nil
        if !twentyFour {
            suffix = hour < 12 ? "AM" : "PM"
            hour = hour % 12 == 0 ? 12 : hour % 12
        }
        let hh = String(format: "%02d", hour)
        let mm = String(format: "%02d", now.minute ?? 0)
        let digitsW = width(hh, scale: 2)
        let total = digitsW * 2 + 8 + 8
        let x = (64 - total) / 2
        let y = (64 - 14) / 2 - (suffix != nil ? 4 : 0)
        draw(hh, into: &px, x: x, y: y, rgb: rgb)
        if (now.second ?? 0) % 2 == 0 {
            let cx = x + digitsW + 4, cy = y + 4
            for (dx, dy) in [(0, 0), (1, 0), (0, 1), (1, 1),
                             (0, 6), (1, 6), (0, 7), (1, 7)] {
                let i = ((cy + dy) * 64 + cx + dx) * 3
                px[i] = rgb.0; px[i + 1] = rgb.1; px[i + 2] = rgb.2
            }
        }
        draw(mm, into: &px, x: x + digitsW + 16, y: y, rgb: rgb)
        if let suffix {
            let sw = width(suffix, scale: 1)
            draw(suffix, into: &px, x: (64 - sw) / 2, y: y + 19,
                 rgb: rgb, scale: 1)
        }
        return UIImage.fromRGB64(Data(px))
    }
