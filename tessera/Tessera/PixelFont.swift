            if ch == "<", i + 1 < chars.count, chars[i + 1] == "3" {
                out.append("\u{2665}")
                skip = true
            } else if let alias = aliases[ch] {
                out.append(alias)
            } else {
                out.append(ch)
            }
        }
        return out
    }

